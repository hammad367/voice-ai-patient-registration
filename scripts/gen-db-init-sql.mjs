#!/usr/bin/env node
// Generates src/lib/db-init-sql.ts — an idempotent (IF NOT EXISTS) version of
// the init migration, used by the runtime self-provisioning bootstrap
// (src/lib/db-bootstrap.ts) when the build-time prisma db push did not run.
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = "/home/z/my-project";
const SCHEMA = `${ROOT}/prisma/schema.prisma`;
const OUT = `${ROOT}/src/lib/db-init-sql.ts`;

process.env.DATABASE_URL ??= "postgresql://u:p@localhost:5432/db";
process.env.DIRECT_DATABASE_URL ??= process.env.DATABASE_URL;

let sql = execSync(
  `bunx prisma migrate diff --from-empty --to-schema-datamodel ${SCHEMA} --script`,
  { cwd: ROOT, env: process.env, encoding: "utf8", maxBuffer: 10 * 1024 * 1024 },
);

sql = sql
  .replace(/CREATE TABLE /g, "CREATE TABLE IF NOT EXISTS ")
  .replace(/CREATE UNIQUE INDEX /g, "CREATE UNIQUE INDEX IF NOT EXISTS ")
  .replace(/CREATE INDEX /g, "CREATE INDEX IF NOT EXISTS ");

if (!sql.includes("CREATE TABLE IF NOT EXISTS")) {
  console.error("transform failed — aborting");
  process.exit(1);
}

const ts = `// ============================================================================
// AUTO-GENERATED by scripts/gen-db-init-sql.mjs — do not edit by hand.
// Idempotent Postgres DDL (IF NOT EXISTS) mirroring prisma/schema.prisma (PostgreSQL default)
// (source migration: prisma/migrations/20260910000000_init/migration.sql).
// Used by src/lib/db-bootstrap.ts to self-provision tables at runtime when the
// build-time "prisma db push" did not run (e.g. default \`next build\` on Vercel).
// If you change the Prisma schema, regenerate: node scripts/gen-db-init-sql.mjs
// ============================================================================

export const DB_INIT_SQL = \`
${sql.trim().replace(/`/g, "\\\\`").replace(/\$\{/g, "\\\${")}\`;
`;

writeFileSync(OUT, ts);
console.log(`written ${OUT} (${ts.length} bytes)`);
